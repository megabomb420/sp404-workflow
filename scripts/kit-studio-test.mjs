import assert from 'node:assert/strict'
import { mkdir, readFile } from 'node:fs/promises'

export async function testKitStudio(browser, base) {
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, acceptDownloads: true })
  context.setDefaultTimeout(10000)
  await context.addInitScript(() => {
    if (!localStorage.getItem('spw.state.v1')) {
      localStorage.setItem('spw.locale', 'pl')
      localStorage.setItem('spw.state.v1', JSON.stringify({ ui: { onboarded: true }, settings: { firmware: 'doom' }, kits: [{ id: 'legacy', name: 'Late beat', items: [], notes: { project: '03', bankPad: 'B4', bpm: '92', text: 'Original session' } }] }))
    }
  })
  const page = await context.newPage(), errors = []
  page.on('pageerror', e => errors.push(e.message))
  const go = async path => { await page.goto(base + path, { waitUntil: 'networkidle' }); await page.locator('.shell').waitFor() }
  const stored = () => page.evaluate(() => JSON.parse(localStorage.getItem('spw.state.v1')))
  const layout = async () => {
    for (const width of [320, 390, 768]) {
      await page.setViewportSize({ width, height: 844 })
      assert.equal(await page.evaluate(() => { const main = document.querySelector('.shell__main'); return document.documentElement.scrollWidth > innerWidth || main.scrollWidth > main.clientWidth + 1 }), false, `Studio overflow at ${width}`)
    }
    await page.setViewportSize({ width: 390, height: 844 })
  }
  try {
    await go('/kit?set=legacy')
    assert.equal(await page.getByRole('textbox', { name: 'Twoje uwagi', exact: true }).inputValue(), 'Original session')
    await page.getByRole('textbox', { name: 'Co zrobisz przy następnej sesji?', exact: true }).fill('Add a transition before the drums return')
    await page.getByRole('button', { name: 'POKAŻ NA NOW', exact: true }).click()
    await go('/')
    assert.match(await page.locator('.resume-sketch').textContent(), /Late beat.*03.*B4.*92 BPM.*Add a transition/s)
    await page.locator('.resume-sketch').getByRole('link', { name: 'SONG MAP →' }).click()
    await page.locator('.song-map[open]').waitFor()
    await page.getByRole('button', { name: 'ZACZNIJ OD PIĘCIU FRAGMENTÓW' }).click()
    await page.getByRole('textbox', { name: 'Pattern / wariacja 1', exact: true }).fill('A1')
    await page.getByRole('textbox', { name: 'Co się zmienia? 1', exact: true }).fill('No drums')
    await page.getByRole('combobox', { name: 'Takty 1', exact: true }).selectOption('8')
    await page.getByRole('textbox', { name: 'Pattern / wariacja 2', exact: true }).fill('A2')
    await page.getByRole('button', { name: 'Przesuń w górę 2', exact: true }).click()
    assert.equal((await stored()).kits[0].studio.song[0].pattern, 'A2')
    await page.getByRole('button', { name: 'Usuń fragment 2', exact: true }).click()
    assert.equal((await stored()).kits[0].studio.song.length, 4)
    await page.getByRole('button', { name: 'COFNIJ USUNIĘCIE', exact: true }).click()
    assert.equal((await stored()).kits[0].studio.song[1].pattern, 'A1')
    for (let i = 0; i < 3; i++) await page.getByRole('button', { name: 'DODAJ FRAGMENT', exact: true }).click()
    assert.equal(await page.getByRole('button', { name: 'DODAJ FRAGMENT', exact: true }).isDisabled(), true)
    await layout()
    await page.reload({ waitUntil: 'networkidle' })
    assert.equal((await stored()).kits[0].studio.song.length, 8)
    assert.equal((await stored()).kits[0].studio.song[1].bars, 8)
    await mkdir('artifacts/companion', { recursive: true })
    await page.locator('.song-map summary').scrollIntoViewIfNeeded()
    await page.screenshot({ path: 'artifacts/companion/song-map.png' })
    await page.locator('.kit-ab summary').click()
    await page.getByRole('textbox', { name: 'Lokalizacja na SP A', exact: true }).fill('B1')
    await page.getByRole('textbox', { name: 'Zmiany / brzmienie A', exact: true }).fill('Straight snare')
    await page.getByRole('textbox', { name: 'Lokalizacja na SP B', exact: true }).fill('B2')
    await page.getByRole('textbox', { name: 'Zmiany / brzmienie B', exact: true }).fill('Late snare')
    await page.getByRole('button', { name: 'WYBIERAM B', exact: true }).click()
    await page.getByRole('textbox', { name: 'Dlaczego ta wersja?', exact: true }).fill('More space around the sample')
    await page.locator('.kit-ab summary').scrollIntoViewIfNeeded()
    await page.screenshot({ path: 'artifacts/companion/kit-ab.png' })
    const before = await stored()
    await go('/settings')
    const event = page.waitForEvent('download')
    await page.getByRole('button', { name: 'POBIERZ KOPIĘ' }).click()
    const backup = JSON.parse(await readFile(await (await event).path(), 'utf8'))
    assert.deepEqual(backup.state.kits[0].studio, before.kits[0].studio)
    assert.equal(backup.state.ui.activeKitId, 'legacy')
    await page.locator('input[type=file]').setInputFiles({ name: 'studio.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(backup)) })
    await page.getByRole('button', { name: 'PRZYWRÓĆ DANE Z KOPII' }).click()
    await go('/kit?set=legacy&tab=ab')
    await page.locator('.shell__top').getByRole('button', { name: 'EN', exact: true }).click()
    assert.doesNotMatch(await page.locator('.kit-studio').innerText(), /[ąćęłńóśźżĄĆĘŁŃÓŚŹŻ]/)
    assert.equal(await page.getByRole('textbox', { name: 'Location on SP B', exact: true }).inputValue(), 'B2')
    assert.equal(await page.getByRole('button', { name: 'CHOOSE B ✓', exact: true }).getAttribute('aria-pressed'), 'true')
    await layout()
    await page.waitForFunction(() => !!navigator.serviceWorker.controller)
    await context.setOffline(true)
    await page.getByRole('textbox', { name: 'What will you do next?', exact: true }).fill('Finish the ending offline')
    await go('/')
    assert.match(await page.locator('.resume-sketch').textContent(), /Finish the ending offline/)
    await page.locator('.resume-sketch').getByRole('link', { name: 'RESUME SKETCH →' }).click()
    await page.getByRole('button', { name: 'MARK AS FINISHED', exact: true }).click()
    await go('/'); assert.equal(await page.locator('.resume-sketch').count(), 0)
    await go('/kit?set=legacy'); await page.getByRole('button', { name: 'PIN TO NOW', exact: true }).click()
    await go('/'); await layout(); await page.screenshot({ path: 'artifacts/companion/resume-sketch.png' })
    assert.equal((await stored()).kits[0].notes.text, 'Original session')
    assert.deepEqual((await stored()).kits[0].studio.variants, before.kits[0].studio.variants)
    assert.deepEqual(errors, [])
    console.log('PASS R7 sketch resume/finish, song map reorder/remove/undo/limit, A/B, legacy notes, backup restore, PL/EN, 320/390/768px and offline')
  } finally { await context.close() }
  const welcome = await browser.newContext({ viewport: { width: 390, height: 844 } })
  try {
    const page = await welcome.newPage(); await page.goto(base + '/onboarding', { waitUntil: 'networkidle' })
    assert.equal(await page.locator('.ob__preview-pad').count(), 16)
    assert.equal((await page.locator('.ob__lcd').textContent()).match(/SP WORKFLOW/g)?.length, 1)
    await page.screenshot({ path: 'artifacts/companion/onboarding-r7.png' })
    console.log('PASS R7 onboarding: one brand label, pad preview')
  } finally { await welcome.close() }
}

export const actionsById: Record<string, ActionRecord> = Object.fromEntries(actions.map((action) => [action.id, action]))

export function resolveWorkflowEntry(entry: WorkflowEntry): WorkflowStep {
  if (!isWorkflowActionRef(entry)) return entry
  const action = actionsById[entry.actionId]
  if (!action) throw new Error(`Unknown action record: ${entry.actionId}`)
  return {
    id: entry.id,
    title: action.title,
    action: entry.context ? `${entry.context} ${action.action}` : action.action,
    buttons: action.buttons,
    path: action.path,
    explanation: action.explanation,
    expectedResult: action.expectedResult,
    commonMistake: action.warning,
    source: action.source,
    kind: action.kind,
  }
}
